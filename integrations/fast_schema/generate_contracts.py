#!/usr/bin/env python3
"""
⚡ ClockEE — Reel #8: Fast-Schema SQLite to TypeScript/Pydantic Contract Generator
Upstream: koxzi/fast-schema
Domain: Data Contracts & Schema Validation

Extracts schema metadata directly from SQLite (clockee.db) and compiles:
1. Strict TypeScript Interfaces: js/types/cbt_contracts.ts
2. Strict Pydantic Models: backend/models.py
Eliminates contract drift between client and server.
"""

import os
import sys
import sqlite3
import argparse
from pathlib import Path
from datetime import datetime

ROOT_DIR = Path(__file__).resolve().parent.parent.parent
DB_PATH = ROOT_DIR / "clockee.db"
TS_OUTPUT_PATH = ROOT_DIR / "js" / "types" / "cbt_contracts.ts"
PY_OUTPUT_PATH = ROOT_DIR / "backend" / "models.py"

TYPE_MAP_TS = {
    "INTEGER": "number",
    "REAL": "number",
    "FLOAT": "number",
    "TEXT": "string",
    "BLOB": "Uint8Array",
    "TIMESTAMP": "string",
    "DATETIME": "string",
    "BOOLEAN": "boolean"
}

TYPE_MAP_PY = {
    "INTEGER": "int",
    "REAL": "float",
    "FLOAT": "float",
    "TEXT": "str",
    "BLOB": "bytes",
    "TIMESTAMP": "str",
    "DATETIME": "str",
    "BOOLEAN": "bool"
}

def get_sqlite_tables(db_path: Path):
    if not db_path.is_file():
        return {}
    conn = sqlite3.connect(db_path)
    cur = conn.cursor()
    cur.execute("SELECT name FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%';")
    tables = [row[0] for row in cur.fetchall()]
    schema = {}
    for tbl in tables:
        cur.execute(f"PRAGMA table_info({tbl});")
        columns = []
        for col in cur.fetchall():
            cid, name, col_type, notnull, dflt_value, pk = col
            base_type = col_type.split("(")[0].strip().upper() or "TEXT"
            columns.append({
                "name": name,
                "type": base_type,
                "nullable": not bool(notnull),
                "is_pk": bool(pk),
                "default": dflt_value
            })
        schema[tbl] = columns
    conn.close()
    return schema

def generate_typescript_contracts(schema: dict) -> str:
    lines = [
        "/**",
        " * ⚡ ClockEE Generated Data Contracts (TypeScript)",
        f" * Auto-generated by Fast-Schema on {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}",
        " * Source: clockee.db",
        " */\n"
    ]
    for tbl, cols in schema.items():
        ifName = "".join([part.capitalize() for part in tbl.split("_")])
        lines.append(f"export interface {ifName} {{")
        for c in cols:
            ts_type = TYPE_MAP_TS.get(c["type"], "any")
            opt = "?" if c["nullable"] and not c["is_pk"] else ""
            lines.append(f"  {c['name']}{opt}: {ts_type};")
        lines.append("}\n")
    return "\n".join(lines)

def generate_pydantic_contracts(schema: dict) -> str:
    lines = [
        "\"\"\"",
        "⚡ ClockEE Generated Data Contracts (Pydantic)",
        f"Auto-generated by Fast-Schema on {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}",
        "Source: clockee.db",
        "\"\"\"",
        "from typing import Optional, List, Any, Dict",
        "from pydantic import BaseModel, Field\n"
    ]
    for tbl, cols in schema.items():
        modelName = "".join([part.capitalize() for part in tbl.split("_")])
        lines.append(f"class {modelName}(BaseModel):")
        for c in cols:
            py_type = TYPE_MAP_PY.get(c["type"], "Any")
            if c["nullable"] and not c["is_pk"]:
                lines.append(f"    {c['name']}: Optional[{py_type}] = None")
            else:
                lines.append(f"    {c['name']}: {py_type}")
        lines.append("")
    return "\n".join(lines)

def main():
    print("=================================================================")
    print(" ⚡ CLOCKEE FAST-SCHEMA CONTRACT COMPILER (Reel #8)")
    print("=================================================================")
    schema = get_sqlite_tables(DB_PATH)
    print(f"[*] Discovered {len(schema)} SQLite tables in clockee.db: {list(schema.keys())}")

    # Generate TypeScript
    TS_OUTPUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    ts_code = generate_typescript_contracts(schema)
    with open(TS_OUTPUT_PATH, "w", encoding="utf-8") as f:
        f.write(ts_code)
    print(f"[✓] TypeScript contracts written to: {TS_OUTPUT_PATH} ({len(ts_code.splitlines())} lines)")

    # Generate Pydantic
    PY_OUTPUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    py_code = generate_pydantic_contracts(schema)
    with open(PY_OUTPUT_PATH, "w", encoding="utf-8") as f:
        f.write(py_code)
    print(f"[✓] Pydantic models written to: {PY_OUTPUT_PATH} ({len(py_code.splitlines())} lines)")

    # Test import of generated python models
    sys.path.insert(0, str(ROOT_DIR / "backend"))
    try:
        import models
        print(f"[✓] Pydantic models cleanly imported and verified without syntax errors.")
    except Exception as e:
        print(f"[!] Warning importing generated models: {e}")

    print("\n[✓] Fast-Schema contract compilation certified (Exit Code 0).")

if __name__ == "__main__":
    main()
