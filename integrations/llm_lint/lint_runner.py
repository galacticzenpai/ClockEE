#!/usr/bin/env python3
"""
ClockEE Package: LLM-Lint Runner (lint_runner.py)
Adapted from JadenRazo/llm-lint (MIT License).

Scans git commit messages, source files, and pull request bodies for
unwanted AI attribution watermarks, commit trailers, and prompt leaks.
"""

import os
import re
import sys
import json
import time
from pathlib import Path

ROOT_DIR = Path(__file__).resolve().parent.parent.parent
REPORTS_DIR = Path(__file__).resolve().parent / "reports"
REPORTS_DIR.mkdir(parents=True, exist_ok=True)

# Detection Rules
RULES = [
    {
        "id": "LLM001",
        "title": "AI Commit Co-Author Trailer",
        "severity": "CRITICAL",
        "pattern": r'Co-[Aa]uthored-[Bb]y:\s*(?:Claude|Copilot|ChatGPT|Gemini|Cursor|Anthropic|OpenAI)',
        "description": "Automated AI co-authorship trailer in commit message."
    },
    {
        "id": "LLM002",
        "title": "AI Tool Watermark / Footer",
        "severity": "HIGH",
        "pattern": r'(?:Generated with|Created by|Crafted with)\s+(?:Claude Code|Cursor|Copilot|v0\.dev|ChatGPT)',
        "description": "Standard AI marketing watermark footer."
    },
    {
        "id": "LLM003",
        "title": "AI Docstring / Comment Marker",
        "severity": "MEDIUM",
        "pattern": r'(?://|#|/\*)\s*(?:Generated by (?:AI|Claude|LLM)|Prompt:\s*["\']|AI-assisted implementation)',
        "description": "Explicit AI prompt or generator notice left in source code."
    },
    {
        "id": "LLM004",
        "title": "AI Agent Tracking Directory",
        "severity": "CRITICAL",
        "pattern": r'(?:\.claude/|\.cursor/|\.devin/)',
        "description": "Local agent metadata directory tracked in source control."
    }
]

class LLMLinter:
    def __init__(self, workspace: Path = ROOT_DIR):
        self.workspace = workspace
        self.findings = []

    def scan_git_history(self, max_commits: int = 50):
        """Scans recent git commit logs for AI attribution trailers."""
        try:
            import subprocess
            cmd = ["git", "log", f"-n{max_commits}", "--pretty=format:%H|%s|%b<EOC>"]
            res = subprocess.run(cmd, cwd=str(self.workspace), capture_output=True, text=True, errors="ignore")
            if res.returncode == 0:
                raw_commits = res.stdout.split("<EOC>")
                for raw in raw_commits:
                    raw = raw.strip()
                    if not raw:
                        continue
                    parts = raw.split("|", 2)
                    commit_hash = parts[0]
                    subject = parts[1] if len(parts) > 1 else ""
                    body = parts[2] if len(parts) > 2 else ""
                    full_msg = f"{subject}\n{body}"

                    for r in RULES:
                        if re.search(r["pattern"], full_msg, re.I):
                            self.findings.append({
                                "rule_id": r["id"],
                                "severity": r["severity"],
                                "target": f"commit:{commit_hash[:8]}",
                                "context": subject,
                                "message": r["description"]
                            })
        except Exception:
            pass

    def scan_source_files(self):
        """Scans source files (.js, .html, .py, .md) for AI code watermarks."""
        for ext in ["*.js", "*.py", "*.html", "*.md"]:
            for file in self.workspace.glob(ext):
                if "vendor" in file.parts or ".git" in file.parts or "node_modules" in file.parts:
                    continue
                try:
                    rel_name = str(file.relative_to(self.workspace))
                    with open(file, "r", encoding="utf-8", errors="ignore") as f:
                        for idx, line in enumerate(f, 1):
                            s_line = line.strip()
                            for r in RULES:
                                if r["id"] in ["LLM002", "LLM003"]:
                                    if re.search(r["pattern"], s_line, re.I):
                                        self.findings.append({
                                            "rule_id": r["id"],
                                            "severity": r["severity"],
                                            "target": f"{rel_name}:{idx}",
                                            "context": s_line[:100],
                                            "message": r["description"]
                                        })
                except Exception:
                    pass

    def sanitize_commit_message(self, commit_msg_content: str) -> str:
        """Strips Co-Authored-By and Generated-With lines cleanly."""
        cleaned_lines = []
        for line in commit_msg_content.splitlines():
            # Check against LLM001 and LLM002
            if re.search(RULES[0]["pattern"], line, re.I) or re.search(RULES[1]["pattern"], line, re.I):
                continue
            cleaned_lines.append(line)
        return "\n".join(cleaned_lines).strip() + "\n"

    def install_git_hook(self):
        """Installs a local git commit-msg hook to strip AI watermarks automatically."""
        hooks_dir = self.workspace / ".git" / "hooks"
        if not hooks_dir.exists():
            return False, "No .git/hooks directory found."

        hook_file = hooks_dir / "commit-msg"
        hook_script = f"""#!/bin/sh
# ClockEE LLM-Lint commit-msg hook
# Automatically cleans AI attribution trailers before commit is finalized
python "{Path(__file__).resolve()}" sanitize-commit "$1"
exit 0
"""
        with open(hook_file, "w", encoding="utf-8", newline="\n") as f:
            f.write(hook_script)

        # Make executable on unix-like environments if possible
        try:
            os.chmod(hook_file, 0o755)
        except Exception:
            pass
        return True, str(hook_file)

    def run_full_scan(self):
        self.findings = []
        self.scan_git_history()
        self.scan_source_files()

        report = {
            "timestamp": time.strftime("%Y-%m-%d %H:%M:%S"),
            "tool": "llm-lint (JadenRazo/llm-lint)",
            "total_findings": len(self.findings),
            "findings": self.findings
        }

        out_json = REPORTS_DIR / f"llm_lint_report_{int(time.time())}.json"
        with open(out_json, "w", encoding="utf-8") as f:
            json.dump(report, f, indent=2)

        return report, out_json

if __name__ == "__main__":
    cmd = sys.argv[1] if len(sys.argv) > 1 else "scan"
    linter = LLMLinter()

    if cmd == "scan":
        report, out_file = linter.run_full_scan()
        print("=" * 68)
        print(" LLM-LINT: AI WATERMARK & PROVENANCE SANITIZER")
        print("=" * 68)
        print(f"Total AI Markers Detected : {report['total_findings']}")
        print(f"Report File               : {out_file}")
        print("=" * 68)
        if report["findings"]:
            for f in report["findings"][:10]:
                print(f"[{f['severity']}] {f['rule_id']} at {f['target']}: {f['message']}")
                print(f"   Context: {f['context']}\n")
        else:
            print("✅ Repository is 100% clean of AI attribution trailers and watermarks.")
        print("=" * 68)

    elif cmd == "sanitize-commit":
        if len(sys.argv) < 3:
            sys.exit(0)
        msg_file = Path(sys.argv[2])
        if msg_file.exists():
            original = msg_file.read_text(encoding="utf-8", errors="ignore")
            cleaned = linter.sanitize_commit_message(original)
            msg_file.write_text(cleaned, encoding="utf-8")

    elif cmd == "install-hook":
        ok, path = linter.install_git_hook()
        if ok:
            print(f"✅ LLM-Lint commit-msg hook installed at: {path}")
        else:
            print(f"❌ Failed to install hook: {path}")
