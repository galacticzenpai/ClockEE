#!/usr/bin/env python3
"""
ClockEE Package: Dray Cross-Model Bridge & Session Linker
Adapted from Dray (withdray.com).

Enables seamless context handoffs across models (Claude, ChatGPT, Gemini, Codex)
when hitting usage limits or switching between specialized coding agents.
"""

import os
import sys
import json
import time
import hashlib
import subprocess
from pathlib import Path

ROOT_DIR = Path(__file__).resolve().parent.parent.parent
SESSIONS_DIR = Path(__file__).resolve().parent / "sessions"
SESSIONS_DIR.mkdir(parents=True, exist_ok=True)
ACTIVE_LINK_FILE = SESSIONS_DIR / "active_link.json"

class DrayBridge:
    def __init__(self, workspace: Path = ROOT_DIR):
        self.workspace = workspace

    def get_git_context(self):
        """Captures recent modified files and last commit message."""
        try:
            status_res = subprocess.run(["git", "status", "--short"], cwd=str(self.workspace), capture_output=True, text=True)
            diff_res = subprocess.run(["git", "diff", "--stat"], cwd=str(self.workspace), capture_output=True, text=True)
            head_res = subprocess.run(["git", "log", "-1", "--oneline"], cwd=str(self.workspace), capture_output=True, text=True)
            return {
                "modified_files": [line.strip() for line in status_res.stdout.splitlines() if line.strip()],
                "diff_stat": diff_res.stdout.strip(),
                "last_commit": head_res.stdout.strip()
            }
        except Exception:
            return {"modified_files": [], "diff_stat": "", "last_commit": ""}

    def create_link_snapshot(self, task_description: str, originating_model: str = "Claude", metadata: dict = None):
        """Generates a portable /link snapshot that any successor model can ingest."""
        timestamp = time.strftime("%Y-%m-%d %H:%M:%S")
        link_id = f"link_{int(time.time())}_{hashlib.md5(task_description.encode()).hexdigest()[:6]}"
        git_ctx = self.get_git_context()

        snapshot = {
            "link_id": link_id,
            "timestamp": timestamp,
            "originating_model": originating_model,
            "task_description": task_description,
            "git_state": git_ctx,
            "protected_boundaries": [
                "Question bank database schemas",
                "Payment and auth credentials in env.js",
                "Unrelated frontend files"
            ],
            "metadata": metadata or {},
            "status": "READY_FOR_HANDOFF"
        }

        # Save snapshot
        snapshot_path = SESSIONS_DIR / f"{link_id}.json"
        with open(snapshot_path, "w", encoding="utf-8") as f:
            json.dump(snapshot, f, indent=2)

        # Update active pointer
        with open(ACTIVE_LINK_FILE, "w", encoding="utf-8") as f:
            json.dump(snapshot, f, indent=2)

        return snapshot, snapshot_path

    def resume_link(self, target_link: str = None):
        """Reads a link snapshot and outputs the formatted context injection prompt."""
        if target_link:
            target_path = SESSIONS_DIR / (f"{target_link}.json" if not target_link.endswith(".json") else target_link)
        else:
            target_path = ACTIVE_LINK_FILE

        if not target_path.exists():
            return None, f"Link snapshot not found: {target_path}"

        with open(target_path, "r", encoding="utf-8") as f:
            snapshot = json.load(f)

        prompt = f"""
================================================================================
 DRAY CONTEXT LINK RESUMPTION PROMPT
 (Generated by {snapshot['originating_model']} -> Ingesting Model: Successor)
================================================================================
Link ID: {snapshot['link_id']}
Timestamp: {snapshot['timestamp']}
Original Task: {snapshot['task_description']}

--- REPOSITORY RECENT STATE ---
Last Commit: {snapshot['git_state'].get('last_commit', 'N/A')}
Modified Files:
{chr(10).join('  - ' + f for f in snapshot['git_state'].get('modified_files', [])) or '  (None)'}

--- PROTECTED SYSTEM BOUNDARIES ---
{chr(10).join('  * DO NOT MODIFY: ' + b for b in snapshot.get('protected_boundaries', []))}

--- INSTRUCTION FOR RESUMING AGENT ---
Read the above context. Resume execution on '{snapshot['task_description']}' directly from where {snapshot['originating_model']} paused without modifying protected boundaries.
================================================================================
"""
        return snapshot, prompt

if __name__ == "__main__":
    bridge = DrayBridge()
    cmd = sys.argv[1] if len(sys.argv) > 1 else "status"

    if cmd == "link":
        task = sys.argv[2] if len(sys.argv) > 2 else "Routine mesh sync and refactor"
        model = sys.argv[3] if len(sys.argv) > 3 else "Claude"
        snap, path = bridge.create_link_snapshot(task, model)
        print("=" * 68)
        print(" DRAY /LINK SNAPSHOT CREATED")
        print("=" * 68)
        print(f"Link ID    : {snap['link_id']}")
        print(f"Origin     : {snap['originating_model']}")
        print(f"Task       : {snap['task_description']}")
        print(f"Saved Path : {path}")
        print("=" * 68)

    elif cmd == "resume":
        target = sys.argv[2] if len(sys.argv) > 2 else None
        snap, prompt = bridge.resume_link(target)
        if snap:
            print(prompt)
        else:
            print(f"Error: {prompt}")

    elif cmd == "status":
        if ACTIVE_LINK_FILE.exists():
            with open(ACTIVE_LINK_FILE, "r", encoding="utf-8") as f:
                cur = json.load(f)
            print("=" * 68)
            print(" DRAY ACTIVE CROSS-MODEL LINK STATUS")
            print("=" * 68)
            print(f"Active Link ID : {cur['link_id']}")
            print(f"Created At     : {cur['timestamp']}")
            print(f"Active Task    : {cur['task_description']}")
            print(f"Model Origin   : {cur['originating_model']}")
            print("=" * 68)
        else:
            print("No active /link snapshot found. Create one with: python dray_bridge.py link")
